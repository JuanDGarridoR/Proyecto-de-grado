package com.proyectogrado.acompanante_service.auditoria;

import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.context.event.ApplicationReadyEvent;
import org.springframework.context.event.EventListener;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;
import org.springframework.web.servlet.HandlerInterceptor;

import java.time.LocalDateTime;
import java.time.ZoneId;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Registro de auditoría de los datos de salud (Ley 1581 de 2012: los datos
 * de salud son sensibles). Cada vez que alguien que no es la propia persona
 * mayor consulta, crea, edita o borra sus datos de salud por este servicio,
 * queda una fila en la tabla auditoria_salud: quién (id y rol), de quién,
 * qué recurso, qué acción, cuándo (hora de Colombia) y si se le permitió
 * (el estado HTTP; un 403 es un intento sin vínculo).
 *
 * La misma tabla la llenan salud-service, acompanante-service y
 * analitica-service, cada uno con sus reglas (REGLAS). Se registra después
 * de responder: si guardar el registro falla, la persona no lo nota y queda
 * un aviso en los logs.
 */
@Component
public class AuditoriaSaludInterceptor implements HandlerInterceptor {

    private static final Logger log = LoggerFactory.getLogger(AuditoriaSaludInterceptor.class);

    private static final ZoneId ZONA = ZoneId.of("America/Bogota");

    /** Ruta de un dato de salud y recurso al que corresponde. El grupo 1, si existe, es el id de la persona mayor. */
    record Regla(Pattern patron, String recurso) {
    }

    static final List<Regla> REGLAS = List.of(
            // Seguimiento del acompañante. Los contactos no son datos de salud.
            new Regla(Pattern.compile("^/api/acompanante/seguimiento/(\\d+)/signos-vitales$"), "SIGNOS_VITALES"),
            new Regla(Pattern.compile("^/api/acompanante/seguimiento/(\\d+)/medicamentos$"), "MEDICAMENTOS"),
            new Regla(Pattern.compile("^/api/acompanante/seguimiento/(\\d+)/citas-medicas$"), "CITAS_MEDICAS")
    );

    private static final Map<String, String> ACCIONES = Map.of(
            "GET", "CONSULTA",
            "POST", "CREACION",
            "PUT", "EDICION",
            "PATCH", "EDICION",
            "DELETE", "BORRADO"
    );

    private final JdbcTemplate jdbc;

    public AuditoriaSaludInterceptor(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    /** Crea la tabla si no existe. SQL que entienden PostgreSQL y H2 (las pruebas). */
    @EventListener(ApplicationReadyEvent.class)
    public void crearTablaSiFalta() {
        try {
            jdbc.execute("""
                    CREATE TABLE IF NOT EXISTS auditoria_salud (
                        id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        fecha TIMESTAMP NOT NULL,
                        id_usuario INTEGER NOT NULL,
                        rol VARCHAR(30),
                        id_persona_mayor INTEGER,
                        recurso VARCHAR(40) NOT NULL,
                        accion VARCHAR(20) NOT NULL,
                        metodo VARCHAR(10) NOT NULL,
                        ruta VARCHAR(255) NOT NULL,
                        estado INTEGER NOT NULL
                    )""");
            jdbc.execute("CREATE INDEX IF NOT EXISTS idx_auditoria_salud_persona ON auditoria_salud (id_persona_mayor)");
        } catch (Exception e) {
            // Puede pasar si otro servicio la está creando en ese mismo instante.
            log.warn("No se pudo crear la tabla auditoria_salud: {}", e.getMessage());
        }
    }

    @Override
    public void afterCompletion(HttpServletRequest request, HttpServletResponse response, Object handler, Exception ex) {
        String accion = ACCIONES.get(request.getMethod());
        Integer idUsuario = entero(request.getHeader("X-User-Id"));
        if (accion == null || idUsuario == null) {
            return;
        }

        String ruta = request.getRequestURI();
        for (Regla regla : REGLAS) {
            Matcher coincidencia = regla.patron().matcher(ruta);
            if (!coincidencia.matches()) {
                continue;
            }

            Integer idPersonaMayor = coincidencia.groupCount() >= 1 ? entero(coincidencia.group(1)) : null;
            // La propia persona mayor viendo lo suyo no se registra.
            if (idUsuario.equals(idPersonaMayor)) {
                return;
            }

            int estado = ex != null && response.getStatus() < 400 ? 500 : response.getStatus();
            registrar(idUsuario, request.getHeader("X-User-Rol"), idPersonaMayor, regla.recurso(),
                    accion, request.getMethod(), ruta, estado);
            return;
        }
    }

    private void registrar(Integer idUsuario, String rol, Integer idPersonaMayor, String recurso,
                           String accion, String metodo, String ruta, int estado) {
        try {
            jdbc.update("""
                    INSERT INTO auditoria_salud
                        (fecha, id_usuario, rol, id_persona_mayor, recurso, accion, metodo, ruta, estado)
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)""",
                    LocalDateTime.now(ZONA), idUsuario, rol == null || rol.isBlank() ? null : rol,
                    idPersonaMayor, recurso, accion, metodo, ruta, estado);
        } catch (Exception e) {
            log.warn("No se pudo guardar el registro de auditoría de {} {}: {}", metodo, ruta, e.getMessage());
        }
    }

    private static Integer entero(String texto) {
        try {
            return texto == null ? null : Integer.valueOf(texto.trim());
        } catch (NumberFormatException e) {
            return null;
        }
    }
}
