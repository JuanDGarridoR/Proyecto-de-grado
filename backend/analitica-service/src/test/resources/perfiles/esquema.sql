-- Tablas que lee DatosPerfiles, solo con las columnas que usa. En la base
-- real las crean los demás servicios (ddl-auto=update). Los datos los
-- inserta PerfilesControllerTest, con fechas relativas a hoy.

CREATE TABLE usuario (
    id_usuario       INTEGER PRIMARY KEY,
    nombre_usuario   VARCHAR(255),
    fecha_nacimiento DATE,
    correo           VARCHAR(255),
    celular          VARCHAR(30),
    id_organizacion  INTEGER,
    activo           BOOLEAN
);

CREATE TABLE persona_mayor (
    id_usuario INTEGER PRIMARY KEY,
    vive_solo  BOOLEAN
);

CREATE TABLE persona_mayor_organizacion (
    id_persona_mayor INTEGER,
    id_organizacion  INTEGER,
    estado           VARCHAR(30),
    PRIMARY KEY (id_persona_mayor, id_organizacion)
);

CREATE TABLE persona_mayor_acompanante (
    id_persona_mayor INTEGER,
    id_acompanante   INTEGER,
    estado           VARCHAR(30),
    PRIMARY KEY (id_persona_mayor, id_acompanante)
);

CREATE TABLE condicion_salud (
    id_condicion_salud INTEGER PRIMARY KEY,
    tipo               VARCHAR(20),
    nombre             VARCHAR(120)
);

CREATE TABLE persona_mayor_condicion_salud (
    id_persona_mayor_condicion_salud INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona_mayor                 INTEGER,
    id_condicion_salud               INTEGER,
    severidad                        VARCHAR(20)
);

CREATE TABLE medicamento (
    id_medicamento   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona_mayor INTEGER,
    activo           BOOLEAN,
    fecha_fin        DATE
);

CREATE TABLE signo_vital (
    id_signo_vital          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona_mayor        INTEGER,
    fecha_hora              TIMESTAMP,
    presion_sistolica       INTEGER,
    presion_diastolica      INTEGER,
    frecuencia_cardiaca     INTEGER,
    temperatura             DOUBLE PRECISION,
    saturacion_oxigeno      INTEGER,
    peso                    DOUBLE PRECISION,
    estatura                DOUBLE PRECISION
);

CREATE TABLE cita_medica (
    id_cita          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona_mayor INTEGER,
    fecha            DATE,
    acompanamiento   VARCHAR(20)
);

CREATE TABLE emergencia (
    id_emergencia    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona_mayor INTEGER,
    fecha_hora       TIMESTAMP
);

CREATE TABLE gusto (
    id_gusto  INTEGER PRIMARY KEY,
    nombre    VARCHAR(255),
    categoria VARCHAR(20)
);

CREATE TABLE persona_mayor_gusto (
    id_persona_mayor INTEGER,
    id_gusto         INTEGER,
    PRIMARY KEY (id_persona_mayor, id_gusto)
);

CREATE TABLE actividad (
    id_actividad    INTEGER PRIMARY KEY,
    id_organizacion INTEGER
);

CREATE TABLE participacion (
    id_persona_mayor INTEGER,
    id_actividad     INTEGER,
    asistio          BOOLEAN,
    PRIMARY KEY (id_persona_mayor, id_actividad)
);
